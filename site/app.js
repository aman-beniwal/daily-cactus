// Best-effort section name for a frontpage story (frontpage stories carry no
// slug of their own in the schema; look them up by url against the sections).
function sectionNameForFrontpage(ed, story) {
  for (const sec of ed.sections || []) {
    for (const s of sec.stories || []) {
      if (s.url && story.url && s.url === story.url) return sec.name;
    }
  }
  return null;
}

// Home-section SLUG for a lead/frontpage story (matched by url), for the
// feedback id so votes on front-page stories map to a topic. Null if unmatched.
function sectionSlugForFrontpage(ed, story) {
  for (const sec of ed.sections || []) {
    for (const s of sec.stories || []) {
      if (s.url && story.url && s.url === story.url) return sec.slug;
    }
  }
  return null;
}

// pinDate: true when the reader picked this date (or arrived on a ?date= link),
// false on the implicit "give me the newest one" load.
async function loadEdition(date, pinDate) {
  $("#paper").innerHTML = `<p class="status">Loading ${esc(date)}&hellip;</p>`;
  try {
    const path = date === "__fixture__" ? "dev-fixture.json" : `editions/${date}.json`;
    const r = await fetch(path, { cache: "no-cache" });
    if (!r.ok) throw new Error(r.status);
    const ed = await r.json();
    renderEdition(ed);
    const sel = $("#datepick");
    if (sel && date !== "__fixture__") sel.value = date;
    // Only stamp ?date= when the reader actually CHOSE a date. Stamping it on
    // the default load rewrote the address bar to the newest date on every
    // visit, so any bookmark or shared link froze to whatever edition happened
    // to be current that morning — the bare URL already resolves to the latest
    // edition via editions/index.json, and now it stays that way.
    if (date !== "__fixture__" && pinDate) {
      history.replaceState(null, "", `?date=${date}`);
    }
  } catch (e) {
    $("#paper").innerHTML = `<p class="status">Couldn't load the ${esc(date)} edition.</p>`;
  }
}

async function init() {
  // Dev-only fixture path — harmless in prod, never linked from the UI.
  const params = new URLSearchParams(location.search);
  if (params.get("fixture") === "1") {
    $("#datebar").style.visibility = "hidden";
    loadEdition("__fixture__");
    setupKeyboardNav();
    return;
  }

  let manifest = { editions: [] };
  try {
    const r = await fetch("editions/index.json", { cache: "no-cache" });
    if (r.ok) manifest = await r.json();
  } catch (e) { /* no manifest yet */ }

  const eds = (manifest.editions || []).slice().sort((a, b) =>
    a.date < b.date ? 1 : -1); // newest first

  if (eds.length) {
    const sel = $("#datepick");
    sel.innerHTML = eds.map((e) =>
      `<option value="${esc(e.date)}">${esc(e.date)}${e.lead ? " — " + esc(e.lead.replace(/==|__/g, "").slice(0, 60)) : ""}</option>`
    ).join("");
    sel.addEventListener("change", () => loadEdition(sel.value, true));
    $("#datebar").style.visibility = "visible";
  }

  const param = params.get("date");
  const start = param || (eds[0] && eds[0].date);
  renderVoteBar();
  if (start) loadEdition(start, Boolean(param));
  else $("#paper").innerHTML = `<p class="status">No editions published yet. Check back after the next run.</p>`;

  setupKeyboardNav();
  setupNavAutoHide();
  showMobileNotice();
}

// Nav bar auto-hide: slides up when the reader scrolls down, returns on scroll
// up. Always shown near the very top. rAF-throttled; small delta kills jitter.
// Nav bar: fixed at the top on desktop (never hides). On mobile it stays in
// place until you scroll PAST it (a sentinel just above it detects when it
// becomes stuck), then hides on scroll-down and returns on scroll-up. A short
// suppression window stops a programmatic scroll (e.g. "Show less") from popping
// the nav back into view.
window.daily._navSuppressUntil = 0;
function setupNavAutoHide() {
  const nav = $("#nav");
  if (!nav) return;
  // 1px sentinel right before the nav: while it's visible the nav isn't stuck.
  const sentinel = document.createElement("div");
  sentinel.setAttribute("aria-hidden", "true");
  sentinel.style.cssText = "height:1px;margin-bottom:-1px";
  nav.parentNode.insertBefore(sentinel, nav);
  let stuck = false;
  new IntersectionObserver(([e]) => {
    stuck = !e.isIntersecting;
    if (!stuck) nav.classList.remove("nav-hidden");
  }, { threshold: 0 }).observe(sentinel);

  let lastY = window.scrollY, ticking = false;
  const update = () => {
    ticking = false;
    if (window.innerWidth >= 700) { nav.classList.remove("nav-hidden"); return; } // desktop: fixed
    if (Date.now() < window.daily._navSuppressUntil) { lastY = window.scrollY; return; }
    const y = window.scrollY;
    if (!stuck) nav.classList.remove("nav-hidden");
    else if (y > lastY + 6) nav.classList.add("nav-hidden");     // scrolling down, stuck
    else if (y < lastY - 6) nav.classList.remove("nav-hidden");  // scrolling up
    lastY = y;
  };
  addEventListener("scroll", () => {
    if (!ticking) { requestAnimationFrame(update); ticking = true; }
  }, { passive: true });
  addEventListener("resize", () => { if (window.innerWidth >= 700) nav.classList.remove("nav-hidden"); });
}

// On phones, a small toast that fades after 3s: the paper is built for desktop.
function showMobileNotice() {
  if (window.innerWidth >= 700) return;
  const t = document.createElement("div");
  t.className = "mobile-toast";
  t.textContent = "Website optimized for desktop";
  document.body.appendChild(t);
  requestAnimationFrame(() => t.classList.add("show"));
  setTimeout(() => {
    t.classList.remove("show");
    setTimeout(() => t.remove(), 450);
  }, 3000);
}

// keyboard j/k to jump between story cards
function setupKeyboardNav() {
  let idx = -1;
  document.addEventListener("keydown", (e) => {
    const tag = (document.activeElement && document.activeElement.tagName) || "";
    if (tag === "SELECT" || tag === "INPUT" || tag === "TEXTAREA") return;
    if (e.key !== "j" && e.key !== "k") return;
    const cards = Array.from(document.querySelectorAll(".story"));
    if (!cards.length) return;
    idx = e.key === "j" ? Math.min(idx + 1, cards.length - 1) : Math.max(idx - 1, 0);
    cards[idx].scrollIntoView({ behavior: "smooth", block: "center" });
  });
}

