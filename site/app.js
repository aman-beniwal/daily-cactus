const SECTION_ORDER = ["ai", "indian-startups", "deep-tech", "india-deep-tech",
  "climate-energy", "agritech", "health-tech", "global-economics", "india",
  "world", "work-careers", "other-interests", "beyond-your-beat"];

// ---------- main render ----------
function renderEdition(ed) {
  const date = ed.date || "";
  // Reorder sections to the fixed running order (nav + body both follow this,
  // since both iterate ed.sections). Stable for any unlisted/future slug.
  if (Array.isArray(ed.sections)) {
    const rank = (s) => { const i = SECTION_ORDER.indexOf(s.slug); return i < 0 ? 999 : i; };
    ed.sections = ed.sections.map((s, i) => [s, i]).sort((a, b) =>
      (rank(a[0]) - rank(b[0])) || (a[1] - b[1])).map((x) => x[0]);
  }
  const d = new Date(date + "T00:00:00");
  const nice = isNaN(d) ? date
    : d.toLocaleDateString("en-IN", { weekday: "long", year: "numeric", month: "long", day: "numeric" });
  $("#dateline").innerHTML =
    `<span>${esc(nice)}</span> &middot; <span>Edition N&ordm; ${esc(ed.edition ?? "—")}</span> &middot; <span>Jaipur, India</span>`;

  $("#markets").innerHTML = marketsHTML(ed.markets);

  // Nav
  const navItems = [`<a data-target="top">Front Page</a>`];
  (ed.sections || []).forEach((s) => {
    if (s.stories && s.stories.length) navItems.push(`<a data-target="sec-${esc(s.slug)}">${esc(s.name)}</a>`);
  });
  if (ed.opportunities && ed.opportunities.length)
    navItems.push(`<a data-target="sec-opportunities">Opportunities</a>`);
  $("#nav").innerHTML = navItems.join('<span class="sep">&middot;</span>');
  $("#nav").querySelectorAll("a").forEach((a) =>
    a.addEventListener("click", () => {
      const t = a.getAttribute("data-target");
      if (t === "top") window.scrollTo({ top: 0, behavior: "smooth" });
      else document.getElementById(t)?.scrollIntoView({ behavior: "smooth" });
    }));

  // Pass 1: assign every story's derived id + collect a url -> anchor map for
  // brief links (the brief can't reference the story id directly — that id
  // does not survive scripts/assemble_edition.py onto the story object).
  const urlAnchors = new Map();
  const register = (s, anchorId) => { if (s && s.url && !urlAnchors.has(s.url)) urlAnchors.set(s.url, anchorId); };

  const leadId = ed.lead ? storyId(date, "front", 0) : null;
  if (ed.lead) register(ed.lead, leadId);
  const frontpageIds = (ed.frontpage || []).map((s, i) => storyId(date, "front", i + 1));
  (ed.frontpage || []).forEach((s, i) => register(s, frontpageIds[i]));
  // Feedback ids (for the 👍/👎 issue title) carry the story's HOME-SECTION slug
  // so fold_taste.py can attribute a front-page vote to a topic. These are
  // SEPARATE from the DOM/anchor ids above (which stay date/front/i for brief
  // jumps + nav). Falls back to "front" only when a lead has no home section.
  const leadFbId = ed.lead
    ? storyId(date, sectionSlugForFrontpage(ed, ed.lead) || "front", "lead") : null;
  const frontpageFbIds = (ed.frontpage || []).map((s, i) =>
    storyId(date, sectionSlugForFrontpage(ed, s) || "front", "fp" + (i + 1)));
  const sectionIds = (ed.sections || []).map((sec) =>
    (sec.stories || []).map((s, i) => storyId(date, sec.slug, i)));
  (ed.sections || []).forEach((sec, si) =>
    (sec.stories || []).forEach((s, i) => register(s, sectionIds[si][i])));
  const oppIds = (ed.opportunities || []).map((o, i) => storyId(date, "opportunities", i));

  // Fix 6: does this url's FIRST-registered anchor live on the front page?
  // (register() above ran lead/frontpage before sections, so urlAnchors
  // already resolves a front-page url to its front-page anchor even when a
  // section story with the same url registers second and is a no-op.)
  const frontAnchorFor = (url) => {
    if (!url) return null;
    const a = urlAnchors.get(url);
    return a && a.startsWith(`${date}/front/`) ? a : null;
  };

  // Pass 2: build HTML
  let html = "";
  // 3.1: the 2-minute brief is removed. urlAnchors (Pass 1) is still built and
  // used by the section cross-references below, so Pass 1 stays.

  // The lead lives OUTSIDE .grid2: .grid2 is a CSS multi-column container now,
  // and multi-column has no equivalent of grid-column:1/-1 for a full-width
  // child. Keeping it separate also lets the lead float its own photo.
  if (ed.lead) {
    html += `<div class="lead-wrap">${storyCardHTML(ed.lead, {
      lead: true, slug: "front", sectionName: null,
      id: leadFbId, anchorId: leadId, date })}</div>`;
  }
  if (ed.frontpage && ed.frontpage.length) {
    html += `<div class="pack">`;
    (ed.frontpage || []).forEach((s, i) => {
      html += storyCardHTML(s, { lead: false, slug: "front", sectionName: sectionNameForFrontpage(ed, s), id: frontpageFbIds[i], anchorId: frontpageIds[i], date });
    });
    html += `</div>`;
  }

  (ed.sections || []).forEach((sec, si) => {
    if (!sec.stories || !sec.stories.length) return;
    html += sectionHeadHTML(sec.name, sec.slug, si);
    // Split the section's stories: full cards go into the packing grid; stories
    // that already ran on the front page collapse into an "Also up top" strip.
    let cards = "";
    const pointers = [];
    sec.stories.forEach((s, i) => {
      const frontAnchorId = frontAnchorFor(s.url);
      if (frontAnchorId) {
        pointers.push(crossRefStripItem(s, sectionIds[si][i], frontAnchorId));
      } else {
        cards += storyCardHTML(s, { lead: false, slug: sec.slug, sectionName: null, id: sectionIds[si][i], anchorId: sectionIds[si][i], date });
      }
    });
    html += `<div class="pack">${cards}</div>`;
    if (pointers.length) {
      html += `<div class="alsotop"><b>Also up top</b>${pointers.join("")}</div>`;
    }
    html += alsoRailHTML(sec.also);
  });

  if (ed.opportunities && ed.opportunities.length) {
    html += sectionHeadHTML("Opportunities & Events", "opportunities", (ed.sections || []).length);
    html += `<div id="sec-opportunities">`;
    ed.opportunities.forEach((o, i) => { html += oppCardHTML(o, oppIds[i]); });
    html += `</div>`;
  } else {
    // keep the anchor resolvable even when empty, harmless no-op div
  }

  $("#paper").innerHTML = html || `<p class="status">A quiet day &mdash; nothing cleared the bar.</p>`;

  // Section nav targets scroll to the section's head element (layout is a
  // flat sequence of card grids, not nested per-section containers).
  let secIdx = 0;
  (ed.sections || []).forEach((sec) => {
    if (!sec.stories || !sec.stories.length) return;
    const heads = document.querySelectorAll(".sec-head");
    if (heads[secIdx]) heads[secIdx].id = `sec-${sec.slug}`;
    secIdx++;
  });
  if (ed.opportunities && ed.opportunities.length) {
    const heads = document.querySelectorAll(".sec-head");
    if (heads[secIdx]) heads[secIdx].id = "sec-opportunities";
  }

  $("#colophon").innerHTML = `${esc(ed.colophon || "")} &middot; assembled by hand every morning
    <img class="colo-logo" src="assets/logo-cactus.png" alt="" aria-hidden="true">`;

  packAll();
}

// ---------- fixed-column rows ----------
// The grid is pure CSS (flexbox): 2 columns on a laptop, 3 on a wide monitor,
// 1 on a phone, with equal-height rows. The only thing JS decides is which card
// (if any) is a lone leftover on its final row — that one spans the full width
// (.wide) so no trailing space is wasted, matching the "5th article goes wide"
// rule. Everything else (row fill, equal heights, meta-at-bottom) is CSS.
function packAll() {
  // Column count follows the CSS media-query breakpoints (viewport width), so
  // the leftover math matches what the flexbox actually lays out.
  const vw = window.innerWidth;
  const cols = vw >= 1500 ? 3 : vw >= 700 ? 2 : 1;
  document.querySelectorAll(".pack").forEach(pack => {
    const cards = Array.from(pack.children).filter(c => c.classList.contains("story"));
    cards.forEach(c => c.classList.remove("wide", "wide-fig", "wide-txt"));
    if (cols < 2 || !cards.length) return;           // phone: single column, no wide
    if (cards.length % cols === 1) {
      const last = cards[cards.length - 1];
      last.classList.add("wide", last.querySelector(".figure img") ? "wide-fig" : "wide-txt");
    }
  });
}
