// P6: the editor appends a provenance note to summaries it could not fully
// source — "(source unreachable — headline only)" / "(summary from limited
// source text)". Render those as a muted editorial aside, not body prose, so
// the reader can see at a glance that the entry is thin ON PURPOSE rather than
// badly written. Escape FIRST, then wrap, so this can never inject markup; the
// pattern is anchored to the two known flags so ordinary trailing parentheses
// (e.g. "(NYSE: ABC)") are left alone.
const _SRC_FLAG_RE =
  /\s*(\((?:source unreachable[^)]*|summary from limited source text)\))\s*$/i;
function summaryHTML(summary) {
  const raw = String(summary == null ? "" : summary);
  const m = raw.match(_SRC_FLAG_RE);
  if (!m) return hl(raw);
  const body = raw.slice(0, m.index);
  return `${hl(body)} <span class="src-flag">${esc(m[1])}</span>`;
}

// v6 marker pen. The editor wraps the single phrase that carries a story in
// ==double equals==; this turns it into the yellow highlighter that has been
// sitting unused in style.css (.hl) since the renderer was written.
// ALWAYS escapes first, so the marker syntax can never be used to inject
// markup — the only thing that survives is <mark>. Capped at two marks per
// block: past that it stops reading as emphasis and starts reading as noise.
// Two emphasis marks, both escaped FIRST so neither can inject markup:
//   ==text==  yellow marker pen   (headlines — the thing you scan)
//   __text__  black pencil rule   (body — the thing you read)
// Colour carries the meaning: emphasis underlines are BLACK, and every
// clickable underline on the page is BLUE (see a.sk in style.css). So an
// underline never has to be guessed at — blue goes somewhere, black doesn't.
// Two marks per block, max: past that it stops reading as emphasis.
const _HL_RE = /==([^=]{1,120})==/g;
const _UL_RE = /__([^_]{1,120})__/g;
function hl(text) {
  const safe = esc(String(text == null ? "" : text));
  let n = 0, u = 0;
  return safe
    .replace(_HL_RE, (w, p) => (++n <= 2 ? `<mark class="hl">${p}</mark>` : p))
    .replace(_UL_RE, (w, p) => (++u <= 2 ? `<span class="ul">${p}</span>` : p));
}

// v6 summary block: a one-line numbers-first hook, then 3-5 bullets.
// Falls back to the single-paragraph `summary` whenever `points` is absent,
// which is what every edition published before v6 carries — those keep
// rendering byte-for-byte as they do today.
function summaryBlockHTML(s) {
  if (Array.isArray(s.points) && s.points.length) {
    const hook = s.hook ? `<p class="hook">${hl(s.hook)}</p>` : "";
    const pts = s.points.map((p) => `<li>${hl(p)}</li>`).join("");
    const flag = _SRC_FLAG_RE.test(String(s.summary || ""))
      ? `<p class="src-flag-line"><span class="src-flag">${
          esc(String(s.summary).match(_SRC_FLAG_RE)[1])}</span></p>`
      : "";
    return `${hook}<ul class="points">${pts}</ul>${flag}`;
  }
  return `<p class="summary">${summaryHTML(s.summary)}</p>`;
}

function keyStatHTML(s) {
  return s.key_stat ? `<span class="key-stat">${esc(s.key_stat)}</span>` : "";
}

function bodyHTML(s, tabVar) {
  let out = "";
  if (s.signal && s.signal.length) {
    out += `<div class="signal" style="--tabc:var(--${tabVar})"><b>The Signal</b><ul>${
      s.signal.map((b) => `<li>${esc(b)}</li>`).join("")}</ul></div>`;
  } else if (s.takeaway || s.why) {
    // legacy fallback (pre-Signal editions), restyled to Cactus Craft
    if (s.takeaway) out += `<p class="legacy-take"><b>Key takeaway&mdash;</b> ${esc(s.takeaway)}</p>`;
    if (s.why) out += `<div class="legacy-why" style="--tabc:var(--${tabVar})"><b>Why it matters</b>${esc(s.why)}</div>`;
  }
  if (s.editors_read) {
    out += `<div class="signal editors"><b>Editor&rsquo;s read</b>${esc(s.editors_read)}</div>`;
  }
  return out;
}

// Fix 6 (RUN_AUDIT_2026-07-17): a story chosen for the front page also lives
// in its home section's digest entries, and previously rendered as a second,
// near-identical full card there. Section rendering now checks each story's
// url against the front-page anchor map (built in Pass 1 below) and, on a
// match, renders this compact one-line cross-reference instead of a full
// card — back-compatible with old editions (no url on a story just means the
// check never matches, same as before this fix).
function crossRefHTML(s, anchorId, frontAnchorId) {
  const url = s.url ? esc(s.url) : "";
  const headline = url
    ? `<a href="${url}" target="_blank" rel="noopener" style="text-decoration:none;color:inherit">${esc(s.headline)}</a>`
    : esc(s.headline);
  const jump = frontAnchorId
    ? `<a class="sk" href="#${esc(frontAnchorId)}">&uarr; on the front page</a>`
    : `<span>&uarr; on the front page</span>`;
  return `<div class="story card crossref" id="${esc(anchorId)}">
    <span class="crossref-headline">${headline}</span> ${jump}
  </div>`;
}

// A section story that already ran on the front page: shown as a compact strip
// item ("Also up top") rather than a full duplicate card that would eat a whole
// packing slot. Keeps the section's anchor id for jumps.
function crossRefStripItem(s, anchorId, frontAnchorId) {
  const url = s.url ? esc(s.url) : "";
  const headline = url
    ? `<a href="${url}" target="_blank" rel="noopener" style="color:inherit">${esc(s.headline)}</a>`
    : esc(s.headline);
  const jump = frontAnchorId
    ? ` <a class="sk" href="#${esc(frontAnchorId)}">&uarr; on the front page</a>`
    : ` <span style="opacity:.7">&uarr; on the front page</span>`;
  return `<span class="altitem" id="${esc(anchorId)}">${headline}${jump}</span>`;
}

function alsoRailHTML(also) {
  if (!also || !also.length) return "";
  const items = also.map((a) => {
    const url = a.url ? esc(a.url) : "";
    const line = esc(a.line || "");
    const src = a.source ? ` <span style="opacity:.7">&mdash; ${esc(a.source)}</span>` : "";
    return url
      ? `<li><a class="sk" href="${url}" target="_blank" rel="noopener">${line}</a>${src}</li>`
      : `<li>${line}${src}</li>`;
  }).join("");
  return `<div class="also-rail"><h6>Also worth knowing</h6><ul>${items}</ul></div>`;
}

// Top + bottom toggles for the mobile accordion. The top flips Read more / Show
// less; the bottom one lives INSIDE the collapse (so it only shows when open) and
// closes the card, scrolling back to its top.
function collapseToggles(collapseId) {
  return {
    top: `<button type="button" class="card-toggle" aria-expanded="false" ` +
      `aria-controls="${collapseId}" onclick="daily.toggleCard(this)">` +
      `<span class="ct-more">Read more</span><span class="ct-less">Show less</span></button>`,
    bottom: `<button type="button" class="card-toggle card-toggle-bottom" aria-expanded="false" ` +
      `onclick="daily.toggleCard(this)"><span>Show less</span></button>`,
  };
}

// Renders one story <article>. `opts`: {lead, slug, sectionName, id, showTab}
function storyCardHTML(s, opts) {
  const tabVar = colorVar(opts.slug);
  const tag = opts.lead ? "article" : "article";
  const cls = ["story", "card"];
  if (opts.lead) cls.push("lead-story");
  // P5: mark an image-less lead so it reflows to one full-width text column
  if (opts.lead && !s.image) cls.push("no-figure");
  const kicker = [];
  if (opts.showTab !== false) {
    const row1 = [];
    if (opts.lead) {
      row1.push(`<span class="lead-badge">Lead<svg viewBox="0 0 80 34" aria-hidden="true"><use href="#lead-swash"/></svg></span>`);
    }
    if (opts.sectionName) row1.push(`<span class="tab" style="--tabc:var(--${tabVar})">${esc(opts.sectionName)}</span>`);
    if (s.developing) row1.push(`<span class="badge-dev">Developing</span>`);
    if (s.badge) row1.push(`<span class="badge-custom">${esc(s.badge)}</span>`);
    const row2 = s.source ? `<div class="row2">${esc(s.source)}</div>` : "";
    kicker.push(`<div class="kicker"><div class="row1">${row1.join("")}</div>${row2}</div>`);
  }
  const url = s.url ? esc(s.url) : "";
  const headlineHTML = url
    ? `<a href="${url}" target="_blank" rel="noopener" style="text-decoration:none;color:inherit">${hl(s.headline)}</a>`
    : hl(s.headline);
  const meta = `<div class="meta">${
      url ? `<a class="sk" href="${url}" target="_blank" rel="noopener">Read the original &rarr;</a>` : ""
    }${askAIHTML(s)}${thumbsHTML(opts.id, s.headline, opts.date)}</div>`;

  const textBlock = `
        ${kicker.join("")}
        <h5>${headlineHTML}</h5>
        ${keyStatHTML(s)}
        ${summaryBlockHTML(s)}
        ${bodyHTML(s, tabVar)}
        ${meta}`;

  // Carried on the card so the "copy" button can lift the exact prompt the
  // Ask-AI links use, without rebuilding it or blowing the URL budget.
  // "heavy" cards (a photo, or a long read) are the ones the packer lets run
  // wide, so a section reads as a mix of broad and narrow boxes.
  const heavy = !!s.image || String(s.summary || "").length > 240;
  const attrs = `class="${cls.join(" ")}" id="${esc(opts.anchorId)}" ` +
    `data-heavy="${heavy ? 1 : 0}" ` +
    `style="--tabc:var(--${tabVar})"` +
    (s.url ? ` data-ask-prompt="${esc(askPrompt(s))}"` : "");

  const collapseId = `col-${esc(opts.anchorId)}`;
  const tog = collapseToggles(collapseId);

  if (opts.lead) {
    // The lead now collapses on mobile too. The .lead-collapse wrapper is
    // display:contents on desktop, so the float (with photo) and two-column
    // (no photo) desktop layouts render exactly as before; on mobile it becomes
    // the accordion body behind the Read more / Show less toggles.
    if (!s.image) {
      return `<${tag} ${attrs}>
        <div class="lead-head">${kicker.join("")}<h5>${headlineHTML}</h5>${keyStatHTML(s)}</div>
        ${tog.top}
        <div class="lead-collapse" id="${collapseId}">
          <div class="lead-main">${summaryBlockHTML(s)}${meta}</div>
          <div class="lead-side">${bodyHTML(s, tabVar)}</div>
          ${tog.bottom}
        </div>
      </${tag}>`;
    }
    return `<${tag} ${attrs}>
      ${figureHTML(s, true)}
      ${kicker.join("")}
      <h5>${headlineHTML}</h5>
      ${keyStatHTML(s)}
      ${tog.top}
      <div class="lead-collapse" id="${collapseId}">
        ${summaryBlockHTML(s)}
        ${bodyHTML(s, tabVar)}
        ${meta}
        ${tog.bottom}
      </div>
    </${tag}>`;
  }
  // Non-lead: on mobile the body collapses behind a "Read more" toggle
  // (3.2). kicker + headline + key-stat stay visible; summary/signal/meta
  // live in .card-collapse. Desktop CSS keeps .card-collapse always open.
  const cardHead = `${kicker.join("")}
        <h5>${headlineHTML}</h5>
        ${keyStatHTML(s)}`;
  const collapseBody = `${summaryBlockHTML(s)}
        ${bodyHTML(s, tabVar)}
        ${meta}`;
  return `<${tag} ${attrs}>
    ${figureHTML(s, false)}
    ${cardHead}
    ${tog.top}
    <div class="card-collapse" id="${collapseId}"><div>
        ${collapseBody}
        ${tog.bottom}
    </div></div>
  </${tag}>`;
}

function oppCardHTML(o, id) {
  const url = o.url ? esc(o.url) : "";
  const name = url
    ? `<a class="sk" href="${url}" target="_blank" rel="noopener">${esc(o.name)}</a>`
    : esc(o.name);
  const when = o.when ? `<span class="when">${esc(o.when)}</span>` : "";
  const src = o.source ? ` <span style="opacity:.7">&mdash; ${esc(o.source)}</span>` : "";
  return `<div class="opp card" id="${esc(id)}" style="--tabc:var(--sea)">
    ${when}<span>${name} &mdash; ${esc(o.summary)}${src}</span>
  </div>`;
}

function sectionHeadHTML(name, slug, ruleIdx) {
  const tabVar = colorVar(slug);
  // Big serif heading + a rule in the section's own colour (the only accent).
  return `<div class="sec-head" style="--tabc:var(--${tabVar})">
    <h2 class="sec-title">${esc(name)}</h2>
    <span class="sec-rule"></span>
  </div>`;
}

// ---------- brief ----------
function normalizeBriefItems(brief) {
  if (!Array.isArray(brief)) return [];
  return brief.map((b) => (typeof b === "string" ? { line: b } : (b || {})));
}
function briefHTML(brief, urlAnchors) {
  const items = normalizeBriefItems(brief);
  if (!items.length) return "";
  const li = items.map((b) => {
    const line = esc(b.line || "");
    const anchor = b.url && urlAnchors.has(b.url) ? urlAnchors.get(b.url) : null;
    if (anchor) return `<li>${line} <a class="sk" href="#${esc(anchor)}">&darr; jump</a></li>`;
    if (b.url) return `<li>${line} <a class="sk" href="${esc(b.url)}" target="_blank" rel="noopener">&rarr;</a></li>`;
    return `<li>${line}</li>`;
  }).join("");
  return `<div class="card brief-card"><h4>The 2-minute brief</h4><ol>${li}</ol></div>`;
}

